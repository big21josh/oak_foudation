/** Event days in Africa/Harare local time, used to work out "what's next" at check-in. */
export const eventDays = ['2026-11-09', '2026-11-10', '2026-11-11'];

/**
 * The session an attendee should head to next: the next non-break session today (Harare time),
 * or the first session of the day if none are left, or the opening session outside the event dates.
 */
export function nextSession(list: Session[], now = new Date()): Session | undefined {
  const real = list.filter((s) => s.type !== 'Break');
  const date = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Africa/Harare',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(now);
  const clock = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Africa/Harare',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  }).format(now);
  const day = eventDays.indexOf(date) + 1;
  if (day < 1) return real[0];
  const today = real.filter((s) => s.day === day);
  return today.find((s) => s.time >= clock) ?? today[0] ?? real[0];
}
